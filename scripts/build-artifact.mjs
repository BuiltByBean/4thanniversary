/**
 * Rebuilds the single-file version.
 *
 * The app imports the matching engine from src/matching.js so the server can
 * run identical code in room mode. That is right for the deployed game and
 * wrong for pasting into a Claude conversation, which needs exactly one file.
 * This inlines the engine and writes artifact/GuessMyAnswer.single.jsx.
 *
 *   npm run artifact
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");

const engine = read("src/matching.js");
const component = read("src/GuessMyAnswer.jsx");

// Drop the module plumbing: the engine becomes plain top-level declarations.
const inlined = engine
  .replace(/^export const /gm, "const ")
  .replace(/^export function /gm, "function ")
  .replace(/^export async function /gm, "async function ")
  .trim();

const importLine = /^import \{ evaluateBoth \} from "\.\/matching\.js";\n/m;
if (!importLine.test(component)) {
  console.error("Could not find the matching.js import — has the component changed?");
  process.exit(1);
}

const banner = `/* ------------------------------------------------------------------ *
 * GENERATED — do not edit this file.
 * Built by scripts/build-artifact.mjs from src/GuessMyAnswer.jsx plus
 * src/matching.js, so the whole game is one paste-able file.
 * Edit the sources and run: npm run artifact
 * ------------------------------------------------------------------ */

`;

// A replacer FUNCTION, not a string: the engine's contraction table contains
// "$1 are", and in a replacement string that would expand to the match.
const single = component.replace(importLine, "").replace(
  /^(import React[^\n]*\n)/m,
  (whole) => whole + "\n" + inlined + "\n"
);

const outDir = path.join(root, "artifact");
fs.mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, "GuessMyAnswer.single.jsx");
fs.writeFileSync(outFile, banner + single);

const lines = (banner + single).split("\n").length;
console.log(`artifact/GuessMyAnswer.single.jsx written (${lines} lines)`);

// A paste-able file must not import anything but React.
const stray = (banner + single).match(/^import .*/gm) || [];
if (stray.length !== 1 || !stray[0].includes("react")) {
  console.error("Still importing something other than React:", stray);
  process.exit(1);
}
console.log("verified: React is the only import");
